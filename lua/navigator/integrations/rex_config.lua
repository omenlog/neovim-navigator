local utils = require('navigator.utils')

local M = {}

local generated_header = "-- Generated by navigator.nvim.\n THIS MUST NOT BE HANDLE MANUALLY"
local keys_hash_header = "-- navigator.nvim keys hash: "

local modifier_names = {
	a = "alt",
	alt = "alt",
	c = "ctrl",
	ctrl = "ctrl",
	d = "cmd",
	cmd = "cmd",
	m = "alt",
	s = "shift",
	shift = "shift",
}

local key_names = {
	bs = "backspace",
	cr = "enter",
	del = "delete",
	down = "down",
	["end"] = "end",
	esc = "escape",
	home = "home",
	left = "left",
	pagedown = "pagedown",
	pageup = "pageup",
	right = "right",
	space = "space",
	tab = "tab",
	up = "up",
}

local function rex_config_dir()
	local config_home = vim.env.XDG_CONFIG_HOME
	if not config_home or config_home == "" then
		config_home = vim.fn.expand("~/.config")
	end

	return config_home .. "/rex"
end

---@param path string
---@param content string
---@return string|nil err
local function write_file(path, content)
	local result = vim.fn.writefile(vim.split(content, "\n", { plain = true }), path)
	if result ~= 0 then
		return "could not write " .. path
	end
end

local function to_rex_key(key)
	if type(key) ~= "string" or key == "" then
		return nil, "key must be a non-empty string"
	end

	if not key:match("^<.*>$") then
		if #key ~= 1 then
			return nil, "unsupported Neovim key " .. key
		end
		if key:match("%u") then
			return "shift+" .. key:lower()
		end
		return key
	end

	local parts = vim.split(key:sub(2, -2), "-", { plain = true })
	local target = table.remove(parts)
	if not target or target == "" then
		return nil, "unsupported Neovim key " .. key
	end

	local modifiers = {}
	for _, modifier in ipairs(parts) do
		local rex_modifier = modifier_names[modifier:lower()]
		if not rex_modifier then
			return nil, "unsupported Neovim modifier " .. modifier
		end
		table.insert(modifiers, rex_modifier)
	end

	if target:match("^%[.+%]$") then
		-- Rex supports W3C physical-key names such as [KeyH].
	else
		local normalized_target = target:lower()
		target = key_names[normalized_target] or normalized_target
	end

	table.insert(modifiers, target)
	return table.concat(modifiers, "+")
end

---@param keys table<string, string>
---@return string
local function keys_hash(keys)
	return vim.fn.sha256(table.concat({ keys.left, keys.right, keys.up, keys.down }, "\n"))
end

---@param keys table<string, string>
---@return string|nil content
---@return string|nil err
local function render(keys)
	local rex_keys = {}
	local used_keys = {}

	for direction, key in pairs(keys) do
		local rex_key, err = to_rex_key(key)
		if not rex_key then
			return nil, direction .. ": " .. err
		end
		if used_keys[rex_key] then
			return nil, "the " .. direction .. " and " .. used_keys[rex_key] .. " keys both map to " .. rex_key
		end

		used_keys[rex_key] = direction
		rex_keys[direction] = rex_key
	end

	return table.concat({
		generated_header,
		keys_hash_header .. keys_hash(keys),
		"",
		"local terminal = \"com.superlogical.terminal\"",
		"",
		"local function runs_neovim()",
		"\tlocal process = rex.block.call(terminal, \"process\", {})",
		"\treturn process and process.foreground and process.foreground.name == \"nvim\"",
		"end",
		"",
		"local function focus_pane(direction)",
		"\treturn function(ctx)",
		"\t\tif runs_neovim() then",
		"\t\t\treturn false",
		"\t\tend",
		"",
		"\t\tlocal _, err = rex.session.focus_direction({",
		"\t\t\tsession_id = ctx.session_id,",
		"\t\t\tdirection = direction,",
		"\t\t\twrap = true,",
		"\t\t})",
		"\t\tif err then",
		"\t\t\trex.log(\"error\", err)",
		"\t\tend",
		"\t\treturn true",
		"\tend",
		"end",
		"",
		"rex.bind(" .. string.format("%q", rex_keys.left) .. ", focus_pane(\"left\"))",
		"rex.bind(" .. string.format("%q", rex_keys.right) .. ", focus_pane(\"right\"))",
		"rex.bind(" .. string.format("%q", rex_keys.up) .. ", focus_pane(\"up\"))",
		"rex.bind(" .. string.format("%q", rex_keys.down) .. ", focus_pane(\"down\"))",
	}, "\n")
end

---@param path string
---@return boolean
local function exist(path)
	return vim.fn.filereadable(path) == 1
end

--- Create Rex bindings and add their Rex loader when absent.
---@param keys table<string, string>
---@return string|nil err
function M.sync(keys)
	-- rendering content for navigator.lua in rex side
	local content, err = render(keys)
	if not content then
		return err
	end

	-- adding content to navigator.lua
	local directory = rex_config_dir()
	vim.fn.mkdir(directory, "p")

	local navigator_path = directory .. "/navigator.lua"
	local write_navigator = true
	if exist(navigator_path) then
		local navigator_content = table.concat(vim.fn.readfile(navigator_path), "\n")
		if navigator_content:find(keys_hash_header .. keys_hash(keys), 1, true) then
			write_navigator = false
		elseif vim.fn.delete(navigator_path) ~= 0 then
			return "could not delete " .. navigator_path
		end
	end

	local changed = false
	if write_navigator then
		local write_err = write_file(navigator_path, content)
		if write_err then
			return write_err
		end
		changed = true
	end

	-- modifying init.lua in rex to add navigator require
	local init_path = directory .. "/init.lua"
	local init = vim.fn.filereadable(init_path) == 1 and table.concat(vim.fn.readfile(init_path), "\n") or ""
	if not init:find('require("navigator")', 1, true) and not init:find("require('navigator')", 1, true) then
		local require_block = "-- Load navigator.nvim's generated conditional pane bindings.\nrequire(\"navigator\")"
		local init_content_updated = init == "" and require_block or init .. "\n\n" .. require_block
		local write_err = write_file(init_path, init_content_updated)
		if write_err then
			return write_err
		end
		changed = true
	end

	if changed then
		utils.run({ "rex", "config", "reload" }, function(err)
			if err then
				vim.notify(err, vim.log.levels.ERROR)
			end
		end)
	end
end

return M
